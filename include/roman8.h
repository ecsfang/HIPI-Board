// roman8.h -- HP Roman-8 characters 160..255 as ISO 8859-1 (Latin-1), as
// in the HP 92198 manual's Table B-2. Used by the 92198's view (video80.cpp)
// and its text log (display_text.cpp).
#pragma once
#include <cstdint>

namespace hipi {

// Roman-8 160..255 -> ISO 8859-1 (the panel's font), as in the manual's
// Table B-2. Characters Latin-1 doesn't have get the nearest one; 0 =
// undefined (shown as a space); 1 = the solid block (an inverse space).
inline constexpr std::uint8_t kRoman8[96] = {
    0x20, 0xC0, 0xC2, 0xC8, 0xCA, 0xCB, 0xCE, 0xCF,   // A0  sp A` A^ E` E^ E: I^ I:
    0xB4, 0x60, 0x5E, 0xA8, 0x7E, 0xD9, 0xDB, 0xA3,   // A8  ' ` ^ : ~ U` U^ Lira(L)
    0xAF, 0,    0,    0xB0, 0xC7, 0xE7, 0xD1, 0xF1,   // B0  overline - - deg C, c, N~ n~
    0xA1, 0xBF, 0xA4, 0xA3, 0xA5, 0xA7, 'f',  0xA2,   // B8  !i ?i currency pound yen section guilder cent
    0xE2, 0xEA, 0xF4, 0xFB, 0xE1, 0xE9, 0xF3, 0xFA,   // C0  a^ e^ o^ u^ a' e' o' u'
    0xE0, 0xE8, 0xF2, 0xF9, 0xE4, 0xEB, 0xF6, 0xFC,   // C8  a` e` o` u` a: e: o: u:
    0xC5, 0xEE, 0xD8, 0xC6, 0xE5, 0xED, 0xF8, 0xE6,   // D0  A* i^ O/ AE a* i' o/ ae
    0xC4, 0xEC, 0xD6, 0xDC, 0xC9, 0xEF, 0xDF, 0xD4,   // D8  A: i` O: U: E' i: ss O^
    0xC1, 0xC3, 0xE3, 0xD0, 0xF0, 0xCD, 0xCC, 0xD3,   // E0  A' A~ a~ D- d- I' I` O'
    0xD2, 0xD5, 0xF5, 'S',  's',  0xDA, 'Y',  0xFF,   // E8  O` O~ o~ S< s< U' Y: y:
    0xDE, 0xFE, 0,    0,    0,    0,    '-',  0xBC,   // F0  THORN thorn - - - - dash 1/4
    0xBD, 0xAA, 0xBA, 0xAB, 1,    0xBB, 0xB1, 0,      // F8  1/2 a_ o_ << solid >> +- (reserved)
};

}  // namespace hipi
