#!/usr/bin/env python3
# hp41_segments.py -- writes src/hp41_segments.cpp: the HP-41 display's
# character segments as filled triangles, and for each HP-41 code (0..127)
# which of them are lit -- so a character can be drawn at any size (the
# Character table's details box).
#
# From 41charset_x.ttf (next to this script): its .notdef glyph is the
# whole starburst -- 14 segments (and six tiny corner markers, left out);
# each character's glyph is made of some of those same contours, so a
# character's mask is the segments its contours match. The dot, the
# comma's tail and the colon's upper dot come from '.', ',' and ':'
# (drawn right of the character cell, as on the display). Which font
# glyph an HP-41 code uses is read from src/chartable_font.cpp's comments
# ("HP-41 code 12 (font 140)"); a code with none shows every segment.
#
#   python3 resources/fonts/hp41_segments.py   (in the project folder;
#   needs fontTools: pip install fonttools)
import os
import re
import sys
from fontTools.ttLib import TTFont

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.normpath(os.path.join(here, "..", ".."))
font = TTFont(os.path.join(here, "41charset_x.ttf"))
glyf = font["glyf"]
cmap = {t.platformID: t.cmap for t in font["cmap"].tables}[3]
ADVANCE = 900                      # a character cell (the font's advance)


def contours(name):
    c, ends, _ = glyf[name].getCoordinates(glyf)
    out, s = [], 0
    for e in ends:
        out.append([tuple(p) for p in c[s:e + 1]])
        s = e + 1
    return out


def triangulate(poly):
    # Ear clipping (the comma's tail isn't convex)
    pts = list(poly)
    area = sum(pts[i][0] * pts[(i + 1) % len(pts)][1] - pts[(i + 1) % len(pts)][0] * pts[i][1]
               for i in range(len(pts)))
    if area < 0:
        pts.reverse()

    def cross(a, b, c):
        return (b[0] - a[0]) * (c[1] - a[1]) - (b[1] - a[1]) * (c[0] - a[0])

    def inside(p, a, b, c):
        return cross(a, b, p) >= 0 and cross(b, c, p) >= 0 and cross(c, a, p) >= 0

    tris = []
    guard = 0
    while len(pts) > 3 and guard < 1000:
        guard += 1
        for i in range(len(pts)):
            a, b, c = pts[i - 1], pts[i], pts[(i + 1) % len(pts)]
            if cross(a, b, c) <= 0:
                continue
            if any(inside(p, a, b, c) for p in pts if p not in (a, b, c)):
                continue
            tris.append((a, b, c))
            del pts[i]
            break
        else:
            break
    if len(pts) == 3:
        tris.append(tuple(pts))
    return tris


def centre(p):
    return (sum(x for x, _ in p) / len(p), sum(y for _, y in p) / len(p))


segs = [c for c in contours(".notdef") if len(c) > 3]          # (the corner markers: 3 points)
assert len(segs) == 14, len(segs)

src = open(os.path.join(root, "src", "chartable_font.cpp")).read()
fmap = {int(a): int(b) for a, b in re.findall(r"HP-41 code (\d+) \(font (\d+)\)", src)}


def glyph(code):
    return contours(cmap[0xF000 + fmap[code]])


# The punctuation: shapes not in the starburst, moved one cell right
def shifted(c):
    return [(x + ADVANCE, y) for x, y in c]


dot = shifted(glyph(46)[0])
comma = [shifted(c) for c in glyph(44)]
tail = next(c for c in comma if sorted(c) != sorted(dot))      # (the other one is the dot)
colon = [shifted(c) for c in glyph(58)]
top = next(c for c in colon if sorted(c) != sorted(dot))
shapes = segs + [dot, tail, top]               # 14 segments, 14 dot, 15 comma tail, 16 colon's top
KDOT, KTAIL, KTOP = 14, 15, 16

masks = []
for code in range(128):
    if code not in fmap:
        masks.append((1 << 14) - 1)
        continue
    if code == 46:
        masks.append(1 << KDOT)
        continue
    if code == 44:
        masks.append((1 << KDOT) | (1 << KTAIL))
        continue
    if code == 58:
        masks.append((1 << KDOT) | (1 << KTOP))
        continue
    m = 0
    for c in glyph(code):
        hit = [i for i, s in enumerate(segs) if sorted(s) == sorted(c)]
        if not hit:
            sys.exit("HP-41 code %d: a contour that isn't a segment" % code)
        m |= 1 << hit[0]
    masks.append(m)

tris, first = [], []
for s in shapes:
    first.append(len(tris))
    tris += triangulate(s)
first.append(len(tris))
xs = [p[0] for t in tris for p in t]
ys = [p[1] for t in tris for p in t]

out = []
out.append("// Generated by resources/fonts/hp41_segments.py from resources/fonts/41charset_x.ttf -- do not edit.")
out.append("// The HP-41 display's segments as triangles (font units, y up) and each code's lit ones.")
out.append('#include "hp41_segments.h"')
out.append("")
out.append("namespace hipi {")
out.append("")
out.append("const Hp41Triangle kHp41Triangles[] = {")
for t in tris:
    out.append("    { %s }," % ", ".join("%d, %d" % (x, y) for x, y in t))
out.append("};")
out.append("")
out.append("// Shape k: triangles kHp41ShapeFirst[k] .. kHp41ShapeFirst[k + 1] - 1")
out.append("const std::uint8_t kHp41ShapeFirst[kHp41Shapes + 1] = { %s };" % ", ".join(str(f) for f in first))
out.append("")
out.append("const std::uint32_t kHp41Lit[128] = {")
for i in range(0, 128, 8):
    out.append("    " + " ".join("0x%05X," % m for m in masks[i:i + 8]) + "  // %d.." % i)
out.append("};")
out.append("")
out.append("}  // namespace hipi")
open(os.path.join(root, "src", "hp41_segments.cpp"), "w").write("\n".join(out) + "\n")
print("%d shapes, %d triangles, x %d..%d, y %d..%d" % (len(shapes), len(tris), min(xs), max(xs), min(ys), max(ys)))
